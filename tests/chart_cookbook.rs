//! The cookbook and the key matrix are executable documentation: every fenced
//! `bash` block marked `<!-- cookbook: run -->` in `docs/chart-cookbook.md` is
//! run as written, from the repository root with the built binary on `PATH`
//! and a scratch `TMPDIR`, and must print exactly the `text` block that
//! follows it. The key matrix must equal `sidescope charts schema --format
//! text` under its fixed generated header. Nothing here runs a real producer.

use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

const ROOT: &str = env!("CARGO_MANIFEST_DIR");
const MARKER: &str = "<!-- cookbook: run -->";
const MATRIX_HEADER: &str = "---
title: \"Chart key matrix\"
status: accepted
stage: CURRENT
tags: [reference, charts, generated]
summary: \"Every chart source, card and mapping key with its default, range and rule, generated from the schema command.\"
---

<!-- generated by `just charts-matrix`: do not edit by hand -->

# Chart key matrix

Every key, default, range and rule that chart validation accepts, as printed by `sidescope charts schema --format text`. The command is the source of truth; this file is its checked-in copy, and a test fails when they differ.

";

struct Block {
    line: usize,
    script: String,
    expected: String,
}

fn binary() -> &'static str {
    env!("CARGO_BIN_EXE_sidescope")
}

fn blocks(markdown: &str) -> Vec<Block> {
    let lines: Vec<&str> = markdown.lines().collect();
    let mut found = Vec::new();
    let mut index = 0;
    while index < lines.len() {
        if lines[index].trim() != MARKER {
            index += 1;
            continue;
        }
        let (script, after_script) = fence(&lines, index + 1, "bash");
        let (expected, after_expected) = fence(&lines, after_script, "text");
        found.push(Block {
            line: index + 1,
            script,
            expected,
        });
        index = after_expected;
    }
    found
}

/// The body of the next fence after `from`, which must open with ```lang.
fn fence(lines: &[&str], from: usize, language: &str) -> (String, usize) {
    let mut index = from;
    while index < lines.len() && !lines[index].starts_with("```") {
        assert!(
            lines[index].trim().is_empty()
                || !lines[index].starts_with("<!--") && !lines[index].starts_with('#'),
            "line {}: expected a ```{language} block, found {:?}",
            index + 1,
            lines[index]
        );
        index += 1;
    }
    assert_eq!(
        lines.get(index).copied(),
        Some(format!("```{language}").as_str()),
        "line {}: expected a ```{language} fence",
        index + 1
    );
    let mut body = Vec::new();
    index += 1;
    while !lines[index].starts_with("```") {
        body.push(lines[index]);
        index += 1;
    }
    (body.join("\n"), index + 1)
}

fn scratch(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR"))
        .join(format!("chart-cookbook-{}-{name}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

fn path_with_binary() -> String {
    let directory = Path::new(binary()).parent().unwrap().display().to_string();
    format!("{directory}:{}", std::env::var("PATH").unwrap_or_default())
}

#[test]
fn every_cookbook_block_prints_what_the_cookbook_shows() {
    let jq = Command::new("jq").arg("--version").output();
    assert!(
        jq.is_ok_and(|output| output.status.success()),
        "jq must be installed (it is in the dev shell); the cookbook cannot be verified without it"
    );
    let text = std::fs::read_to_string(format!("{ROOT}/docs/chart-cookbook.md")).unwrap();
    let found = blocks(&text);
    assert!(
        found.len() >= 12,
        "the cookbook shows only {} runnable blocks",
        found.len()
    );
    let tmp = scratch("run");
    for block in &found {
        let output = Command::new("bash")
            .arg("-c")
            .arg(&block.script)
            .current_dir(ROOT)
            .env("PATH", path_with_binary())
            .env("TMPDIR", &tmp)
            .env("HOME", &tmp)
            .env("XDG_CONFIG_HOME", &tmp)
            .stdin(Stdio::null())
            .output()
            .unwrap();
        let stdout = String::from_utf8(output.stdout).unwrap();
        assert_eq!(
            stdout.trim_end(),
            block.expected.trim_end(),
            "block at line {} printed something else; stderr: {}",
            block.line,
            String::from_utf8_lossy(&output.stderr)
        );
        assert_eq!(
            output.status.code(),
            Some(0),
            "block at line {} must end with status 0 (script: {})",
            block.line,
            block.script
        );
    }
}

#[test]
fn the_key_matrix_is_the_generated_schema_text() {
    let output = Command::new(binary())
        .args(["charts", "schema", "--format", "text"])
        .output()
        .unwrap();
    assert_eq!(output.status.code(), Some(0));
    let expected = format!(
        "{MATRIX_HEADER}{}",
        String::from_utf8(output.stdout).unwrap()
    );
    let actual = std::fs::read_to_string(format!(
        "{ROOT}/docs/reference/command-charts/key-matrix.md"
    ))
    .unwrap();
    assert_eq!(
        actual, expected,
        "key-matrix.md is stale: run `just charts-matrix`"
    );
}

#[test]
fn the_cookbook_names_every_error_kind_and_outcome_the_schema_lists() {
    let text = std::fs::read_to_string(format!("{ROOT}/docs/chart-cookbook.md")).unwrap();
    for kind in [
        "invalid-config",
        "missing-executable",
        "spawn",
        "nonzero-exit",
        "timeout",
        "output-bound",
        "cancelled",
        "parse",
        "unsupported-version",
        "invalid-mapping",
        "invalid-dataset",
        "no-observations",
        "no-intervals",
        "no-known-values",
        "card-mismatch",
        "capacity",
        "plotted",
        "unavailable",
    ] {
        assert!(
            text.contains(&format!("`{kind}`")),
            "the troubleshooting flow never names `{kind}`"
        );
    }
}
